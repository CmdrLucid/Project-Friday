#!/usr/bin/env python3
"""Generate docs/CODE_MAP.md (a map of the game's code and data by area / source file) from docs/symbols.json.
Each entry's `src` (set by tools/locate_labels.py --merge) is the file of the lordmir disassembly the label lives in; areas = its first directory.
Nothing here is invented: names + addresses + confidence tiers come from symbols.json, the short area descriptions below are hand-written.
usage: make_code_map.py   (no arguments; rerun after changing symbols.json; check_docs does not need it)"""
import collections, json, os
here = os.path.dirname(os.path.abspath(__file__))
sy = json.load(open(os.path.join(here, "..", "docs", "symbols.json")))["symbols"]

AREA = collections.OrderedDict([
 ("system", "Boot and core services: vector table, ROM header, thunks (`j_...`), VDP / DMA / palette / sound helpers, input, SRAM save game, Sleep and the VBlank / HBlank handlers."),
 ("gamelogic", "The main loop (ResetGame, GameLoop), player movement and floor types, attacks, damage, entity updates, menus' hooks, the map loader glue."),
 ("maps", "Room loading and room data: map / block / heightmap loaders (the strip loaders widescreen relies on), palettes, room flags, custom room actions, sprite lists per room."),
 ("sprites", "Sprite and entity data: sprite behaviours, animation / frame tables, graphics pointers, palettes of sprites."),
 ("script", "Cutscene and character scripts (CS_xxxx, CSA_xxxx, XS_xxxx), shop scripts, text-script data tables."),
 ("scripthandling", "The engine that runs those scripts: ProcessDialogueScriptAction, flag tests, dialogue helpers."),
 ("text", "Text engine: string printing, control characters, the text box, string tables and fonts."),
 ("inventory", "Start menu, item use, equipment, shops' UI, the options screens (this project adds an Options tab here)."),
 ("items", "Item data: names, properties, effects, shop item lists."),
 ("title", "Sega logo, title screen, file select (Start / Copy / Delete), game start (the sword slash)."),
 ("graphics", "Graphics data and loaders: tilesets, fonts, compressed pictures, static screens (lithograph, island map)."),
 ("blocks", "Map block (metatile) data."),
 ("pointertables", "Large pointer tables to data blocks (rooms, tilesets, sprites, strings)."),
 ("landstalker_us.asm", "Binary assets included directly by the main file (palettes, flag tables, graphics, maps, music data): labels defined next to the `incbin` lines."),
 ("ending", "Ending sequence and credits."),
 ("misc", "Odds and ends: Friday animation, region check, equipment palette swap, ..."),
])

by = collections.defaultdict(lambda: collections.defaultdict(list)); other = []
for e in sy:
    src = e.get("src", "")
    if not src: other.append(e); continue
    area, _, f = src.partition("/")
    by[area][src].append(e)

def tier(c): return c.split(" ")[0]
cnt = collections.Counter(tier(e["confidence"]) for e in sy)
out = ["# CODE MAP (generated by tools/make_code_map.py from docs/symbols.json: do not edit by hand)", "",
       "A map of the game by area and source file, for finding your way in the code and for future modding. Names come from the lordmir/landstalker_disasm project; the **addresses** were computed for the US ROM (see INDEX.md 'Symbol rule' for how and how sure). A name tells what the original authors called a routine, not necessarily what we understood about it yet.", "",
       "Confidence tiers (entries): " + ", ".join("`%s` %d" % (k, v) for k, v in cnt.most_common()) + ".", "",
       "Not covered: the sound driver (`code/audio` in the disassembly) is Z80 code in its own address space; it is not part of this 68K map.\n\nHow to read a line: `Name $ADDR` = code or label entry point; the tier is shown only where it is NOT one of the auto-computed ones (`v` = verified by us, `i` = inferred). Data is summarised by count and range.", ""]
def sk(x): return int(x["addr"], 16)
for area, desc in AREA.items():
    files = by.get(area)
    if not files: continue
    allent = [e for fl in files.values() for e in fl]
    lo, hi = min(sk(e) for e in allent), max(sk(e) for e in allent)
    nc = sum(1 for e in allent if e["kind"] == "code"); nd = len(allent) - nc
    out += ["## %s  (`$%06X`-`$%06X`, %d code, %d data labels)" % (area, lo, hi, nc, nd), "", desc, ""]
    for f in sorted(files, key=lambda k: min(sk(e) for e in files[k])):
        ents = sorted(files[f], key=sk); code = [e for e in ents if e["kind"] == "code"]; data = [e for e in ents if e["kind"] != "code"]
        out.append("### `%s`  `$%06X`-`$%06X`  (%d code, %d data)" % (f, sk(ents[0]), sk(ents[-1]), len(code), len(data)))
        if code:
            def mark(e):
                t = tier(e["confidence"]); return " (%s)" % {"verified": "v", "inferred": "i"}.get(t, "") if t in ("verified", "inferred") else ""
            out.append("; ".join("%s `$%06X`%s" % (e["name"], sk(e), mark(e)) for e in code))
        if data:
            out.append("Data: " + ", ".join("%s `$%06X`" % (e["name"], sk(e)) for e in data[:12]) + (" ... (+%d more)" % (len(data) - 12) if len(data) > 12 else ""))
        out.append("")
if other:
    out += ["## Names without a disassembly source (given by this project)", "", "Entries we named ourselves or where the disassembly has no label at that address (RAM variables, inferred roles, game-specific names).", ""]
    def rows(es): return ["; ".join("%s `$%06X` (%s)" % (e["name"], sk(e), tier(e["confidence"])) for e in es[i:i + 30]) for i in range(0, len(es), 30)]   # 30 names per line
    grp = collections.OrderedDict()   # 2026-11-12: one block per address range (was ONE line of ~1500 names), each its own ### heading = a TOC entry
    for e in sorted(other, key=sk):
        a0 = sk(e); key = "RAM" if a0 >= 0xFF0000 else "ROM bank %02X" % (a0 >> 16)   # no $ / 0x range bounds: tools/unknowns.py scan-docs would take them for addresses
        grp.setdefault(key, []).append(e)
    for key, es in grp.items():
        if key.startswith("RAM"):   # RAM is large: split by $1000 pages
            pg = collections.OrderedDict()
            for e in es: pg.setdefault(sk(e) >> 12, []).append(e)
            for p0, pe in pg.items():
                out += ["### `own/RAM page %03Xxxx`  (%d)" % (p0, len(pe))] + rows(pe) + [""]
        else: out += ["### `own/%s`  (%d)" % (key, len(es))] + rows(es) + [""]
# TABLE OF CONTENTS with line numbers (user 2026-11-12: 'sollte unsere Codemap nicht ein Inhaltsverzeichnis haben, wenn Claude sie liest?'): one line per area with its
# line range and every source file's line, so a reader takes the TOC (top of the file) and then only the lines it needs (sed -n 'A,Bp')
def toc(off):
    heads = [(i + off, l) for i, l in enumerate(out) if l.startswith("## ") or l.startswith("### ")]
    areas = [(n, l) for n, l in heads if l.startswith("## ")]; t = ["## Contents (line numbers in this file; read only the part you need: `sed -n 'A,Bp' docs/CODE_MAP.md`)", ""]
    for k, (n, l) in enumerate(areas):
        end = (areas[k + 1][0] - 1) if k + 1 < len(areas) else len(out) + off - pos - 1   # = the last line of the file
        name = l[3:].split("  (")[0]; fs = [(m, h) for m, h in heads if h.startswith("### ") and n < m <= end]
        t.append("- **%s** lines %d-%d%s" % (name, n, end, (": " + ", ".join("%s %d" % (h.split("`")[1].split("/")[-1], m) for m, h in fs)) if fs else ""))
    return t + [""]
pos = 2   # after the title line and its blank line
n0 = len(toc(0))
for _ in range(3):   # the TOC's own length shifts every line below it
    t = toc(pos + n0 + 1); 
    if len(t) == n0: break
    n0 = len(t)
out[pos:pos] = t
open(os.path.join(here, "..", "docs", "CODE_MAP.md"), "w").write("\n".join(out))
print("docs/CODE_MAP.md: %d areas, %d entries, %d without source" % (len([a for a in AREA if a in by]), len(sy), len(other)))
