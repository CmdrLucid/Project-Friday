#!/usr/bin/env python3
"""Names in the runtime diagnostics (idempotent).  usage: patch_symnames.py path/to/genrecomp
Generates src/lk_symtab.c from docs/symbols.json (every `code` / `label` / `data+code` entry; sorted by address) and teaches the console diagnostics to print
the name next to a code address: `$0178C8(UpdateSprites)`, or `$017A10(UpdateSprites+0x148)` for an address inside a function (only the nearest
preceding code symbol within 0x200 bytes, shown with +offset so it is never mistaken for an entry).
Touches: call stack dump (func_table_dump_stack: also used by the WIDE / TALL debug lines, WATCHDOG, guard), `interp: running`, `no function at`,
`RTS to`, GENRECOMP_CALLTRACE lines (`T ...` get `; Name` at the end).  The `$XXXXXX` text stays where it was, so tools/unknowns.py from-log still parses the lines.
LANDSTALKER_NONAMES=1 turns the names off at run time.  Names are guesses of the disassembly authors / of this project: see docs/INDEX.md 'Symbol rule' for the confidence tiers."""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1]

sym = json.load(open(os.path.join(here, "..", "docs", "symbols.json")))["symbols"]
rows = {}
for e in sym:
    if e["kind"] in ("code", "label", "data+code"):
        a = int(e["addr"], 16)
        if a < 0x400000: rows.setdefault(a, e["name"])
src = ["/* generated by tools/patch_symnames.py from docs/symbols.json (do not edit; no ROM data, only names) */",
       "#include <stdint.h>", "#include <stdlib.h>", "#include <stdio.h>", "#include <string.h>",
       "static const struct { uint32_t a; const char *n; } lk_sym_tab[] = {"]
src += ['    {0x%06X, "%s"},' % (a, rows[a]) for a in sorted(rows)]
src += ["};", "#define LK_SYM_N (sizeof(lk_sym_tab) / sizeof(lk_sym_tab[0]))",
        "/* writes \"(Name)\" or \"(Name+0xNN)\" for a code address into b (size n); \"\" when unknown or LANDSTALKER_NONAMES=1 */",
        "const char *lk_symfmt(uint32_t a, char *b, int n) {",
        "    static int off = -1; size_t lo = 0, hi = LK_SYM_N;",
        "    if (off < 0) off = getenv(\"LANDSTALKER_NONAMES\") != NULL;",
        "    b[0] = 0; if (off || a >= 0x400000) return b;",
        "    while (lo < hi) { size_t m = (lo + hi) / 2; if (lk_sym_tab[m].a <= a) lo = m + 1; else hi = m; }",
        "    if (!lo) return b;",
        "    if (lk_sym_tab[lo - 1].a == a) snprintf(b, n, \"(%s)\", lk_sym_tab[lo - 1].n);",
        "    else if (a - lk_sym_tab[lo - 1].a <= 0x200) snprintf(b, n, \"(%s+0x%X)\", lk_sym_tab[lo - 1].n, a - lk_sym_tab[lo - 1].a);",
        "    return b;", "}", ""]
open(os.path.join(root, "src/lk_symtab.c"), "w").write("\n".join(src))
print("lk_symtab.c written: %d names" % len(rows))

p = os.path.join(root, "CMakeLists.txt"); s = open(p).read()
if "src/lk_symtab.c" not in s:
    a = "    src/func_table.c\n"
    assert s.count(a) == 1, "CMakeLists.txt: func_table.c line not found"
    open(p, "w").write(s.replace(a, a + "    src/lk_symtab.c\n", 1)); print("CMakeLists.txt patched: lk_symtab.c")

p = os.path.join(root, "src/func_table.c"); s = open(p).read()
if "lk_symfmt" in s:
    print("func_table.c already patched: lk_symfmt"); sys.exit(0)
def rep(a, b):
    global s
    assert s.count(a) == 1, "func_table.c layout changed: " + a[:60]
    s = s.replace(a, b, 1)
rep("void func_table_dump_stack(FILE *f) {\n    fprintf(f, \"call stack (%d):\", s_call_depth);\n    for (int i = 0; i < s_call_depth && i < 512; i++) fprintf(f, \" $%06X\", s_stack[i]);\n",
    "extern const char *lk_symfmt(uint32_t a, char *b, int n);   /* lk_symtab.c (tools/patch_symnames.py) */\nvoid func_table_dump_stack(FILE *f) {\n    char nb[96];\n    fprintf(f, \"call stack (%d):\", s_call_depth);\n    for (int i = 0; i < s_call_depth && i < 512; i++) fprintf(f, \" $%06X%s\", s_stack[i], lk_symfmt(s_stack[i], nb, sizeof nb));\n")
rep("fprintf(stderr, \"interp: running $%06X on the 68K interpreter (no recompiled function)\\n\", m68k_addr);",
    "char nb[96]; fprintf(stderr, \"interp: running $%06X%s on the 68K interpreter (no recompiled function)\\n\", m68k_addr, lk_symfmt(m68k_addr, nb, sizeof nb));")
rep("fprintf(stderr, \"func_table: no function at $%06X (SP=$%08X), \", m68k_addr, g_m68k.a[7]);",
    "char nb[96]; fprintf(stderr, \"func_table: no function at $%06X%s (SP=$%08X), \", m68k_addr, lk_symfmt(m68k_addr, nb, sizeof nb), g_m68k.a[7]);")
rep("fprintf(stderr, \"func_table: RTS to $%06X (expected $%06X, SP=$%08X) has no function; returning, \",\n                        r, e, g_m68k.a[7] - 4);",
    "char nb1[96], nb2[96]; fprintf(stderr, \"func_table: RTS to $%06X%s (expected $%06X%s, SP=$%08X) has no function; returning, \",\n                        r, lk_symfmt(r, nb1, sizeof nb1), e, lk_symfmt(e, nb2, sizeof nb2), g_m68k.a[7] - 4);")
rep("if (ct_on()) fprintf(stderr, \"T %ld d=%d $%06X ret=$%06X\\n\", platform_frame_number(), s_call_depth, m68k_addr, ret);",
    "if (ct_on()) { char nb[96]; lk_symfmt(m68k_addr, nb, sizeof nb); fprintf(stderr, \"T %ld d=%d $%06X ret=$%06X%s%s\\n\", platform_frame_number(), s_call_depth, m68k_addr, ret, nb[0] ? \" ; \" : \"\", nb); }")
open(p, "w").write(s); print("func_table.c patched: lk_symfmt")
