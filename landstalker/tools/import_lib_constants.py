#!/usr/bin/env python3
"""Entity types, items, story flags and ROM table offsets from Dinopony/landstalker-lib (local clone, default ~/landstalker-lib).
Writes docs/ENTITIES.md, docs/ITEMS.md, docs/FLAGS.md, docs/lib_constants.json and adds the ROM table offsets (constants/offsets.hpp, US ROM)
to docs/symbols.json as kind 'data' where no symbol exists at that address yet (confidence 'library (landstalker-lib offsets.hpp)').
Rooms are done by tools/import_rooms.py.   Usage: python3 tools/import_lib_constants.py [~/landstalker-lib] [--no-symbols]"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import symfile
args = [a for a in sys.argv[1:] if not a.startswith("--")]
LIB = os.path.expanduser(args[0] if args else "~/landstalker-lib")
DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs")
C = os.path.join(LIB, "constants")
HEAD = "Generated by `tools/import_lib_constants.py` from [Dinopony/landstalker-lib](https://github.com/Dinopony/landstalker-lib) (thanks!). "

# entities
codes = {}
for l in open(os.path.join(C, "entity_type_codes.hpp")):
    m = re.match(r"constexpr uint8_t (\w+) = (\d+);", l)
    if m: codes.setdefault(int(m.group(2)), []).append(m.group(1))
jnames = json.load(open(os.path.join(LIB, "assets", "entity_type_names.json")))
ids = sorted(set(codes) | set(range(len(jnames))))
out = ["# Entity types\n", HEAD + "Entity type id (the entity byte at +3B (`SpriteType`) of the 128 byte entity struct; verified 2026-10-23 in rooms 444 and 615, see FORMATS at `$FF5400 + n*$80`, see FORMATS) -> name. "
       "`name` = library's `entity_type_names.json` (index = id), `code` = constant in `entity_type_codes.hpp` (ENEMY_* / ENTITY_*). "
       f"{len(jnames)} names, {len(codes)} codes.\n", "| id | hex | name | code |", "|---|---|---|---|"]
for i in ids:
    out.append(f"| {i} | ${i:02X} | {jnames[i] if i < len(jnames) else ''} | {', '.join(codes.get(i, []))} |")
open(os.path.join(DOCS, "ENTITIES.md"), "w").write("\n".join(out) + "\n")

# items
items = {}
for l in open(os.path.join(C, "item_codes.hpp")):
    m = re.match(r"constexpr uint8_t ITEM_(\w+) = (0x[0-9A-Fa-f]+|\d+);", l)
    if m: items[int(m.group(2), 0)] = m.group(1)
out = ["# Item ids\n", HEAD + "Item id (inventory byte, chest content, shop entry) -> name (`constants/item_codes.hpp`). Our `UseItemTable $008620` keys are these ids.\n",
       "| id | name |", "|---|---|"] + [f"| ${i:02X} | {n} |" for i, n in sorted(items.items())]
open(os.path.join(DOCS, "ITEMS.md"), "w").write("\n".join(out) + "\n")

# flags
flags = []
for l in open(os.path.join(C, "flags.hpp")):
    m = re.match(r"constexpr Flag (\w+)\s*\(0x([0-9A-Fa-f]+),\s*(\d+)\);", l)
    if m: flags.append((int(m.group(2), 16), int(m.group(3)), m.group(1)[5:]))
flags.sort()
out = ["# Story flags\n", HEAD + f"{len(flags)} named flags (`constants/flags.hpp`): byte index + bit in the story flag area. In RAM the area starts at `$FF1000` "
       "(our `EB_GetFlagParams`: d6 = flag byte, a6 = `$FF1000`; the bit numbering = bit number of `btst`/`bset` is assumed, not yet proven here: check with the game before relying on it). "
       "The savegame stores the same bytes.\n", "| byte | bit | RAM (assumed) | name |", "|---|---|---|---|"]
for b, bit, n in flags: out.append(f"| ${b:02X} | {bit} | ${0xFF1000 + b:06X}.{bit} | {n} |")
open(os.path.join(DOCS, "FLAGS.md"), "w").write("\n".join(out) + "\n")

# offsets
offs = {}
txt = open(os.path.join(C, "offsets.hpp")).read()
for m in re.finditer(r"constexpr uint32_t (\w+) = (0x[0-9A-Fa-f]+|\w+);", txt):
    v = m.group(2)
    offs[m.group(1)] = int(v, 16) if v.startswith("0x") else offs.get(v)
json.dump({"source": "Dinopony/landstalker-lib", "items": {k: v for k, v in offs.items() if v is not None},
           "flag_names": {f"{b:02X}.{bit}": n for b, bit, n in flags}, "entity_names": jnames}, open(os.path.join(DOCS, "lib_constants.json"), "w"), indent=0)
added = same = 0
if "--no-symbols" not in sys.argv:
    doc = symfile.load(); have = {int(s["addr"], 16): s for s in doc["symbols"]}
    for k, a in offs.items():
        if a is None or k.endswith("_END") or a in have:
            same += a in have; continue
        nm = "".join(w.capitalize() for w in k.split("_"))
        doc["symbols"].append({"addr": f"0x{a:06X}", "name": "Lib" + nm if a < 0 else nm, "kind": "data",
                               "note": f"{k} in landstalker-lib constants/offsets.hpp (US ROM); table/data start, size from the *_END constant when there is one",
                               "confidence": "library (landstalker-lib offsets.hpp)"}); have[a] = doc["symbols"][-1]; added += 1
    symfile.save(doc)
print(f"entities {len(ids)}, items {len(items)}, flags {len(flags)}, offsets {len(offs)}; symbols added {added}, address already named {same}")
