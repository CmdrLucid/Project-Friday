#!/usr/bin/env python3
"""make_toc.py [--check] [FILE ...] - writes a CONTENTS block with LINE NUMBERS at the top of the big docs (user 2026-11-12: 'sollte unsere Codemap nicht ein
Inhaltsverzeichnis haben wenn Claude sie liest?' -> 'ja bitte genau so' for HANDOFF / INDEX / LESSONS), so a reader takes the first ~40 lines and then
only the part it needs (`sed -n 'A,Bp' FILE | cut -c1-800`).  Default files: docs/HANDOFF.md, docs/INDEX.md, docs/LESSONS.md (CODE_MAP.md gets its own
from make_code_map.py).  The block sits between '<!-- TOC' and '<!-- /TOC -->' right after the title line; everything else is untouched.
--check: exit 1 if a block is missing or stale (check_docs.py runs this; the pre-commit hook rewrites the blocks and stages them)."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__)); DOCS = os.path.join(HERE, "..", "docs")
B0, B1 = "<!-- TOC: generated by tools/make_toc.py (the pre-commit hook keeps it current), do not edit by hand -->", "<!-- /TOC -->"

def short(t, n=90):
    t = re.sub(r"\*\*|`", "", t).strip(); return t if len(t) <= n else t[:n - 3].rstrip() + "..."

def strip_block(lines):
    if len(lines) > 1 and lines[1] == B0:
        try: e = lines.index(B1, 1)
        except ValueError: return lines
        rest = lines[e + 1:]
        if rest and rest[0] == "": rest = rest[1:]
        return lines[:1] + rest
    return lines

def sections(body, off):
    """(line, title, end line) of every '## ' heading; off = line number of body[0]"""
    hs = [(i + off, l[3:]) for i, l in enumerate(body) if l.startswith("## ")]
    return [(n, t, (hs[k + 1][0] - 1) if k + 1 < len(hs) else off + len(body) - 1) for k, (n, t) in enumerate(hs)]

def toc_handoff(body, off, name):
    S = sections(body, off); main = [s for s in S if re.match(r"\d+[a-z]?\. ", s[1]) and not s[1].startswith("0a")]
    ent = sorted(((int(m.group(1)), n, t) for n, t, _ in S for m in [re.match(r"0a(\d+)\. ", t)] if m), reverse=True)
    out = ["**Contents of %s** (line numbers; read a part with `sed -n 'A,Bp' docs/%s | cut -c1-800`; the 0a entries are NOT in number order in the file)" % (name, name), ""]
    out += ["- %s: lines %d-%d" % (short(t, 60), n, e) for n, t, e in main]
    nx = [(i + off, l) for i, l in enumerate(body) if re.match(r"-\d+\. ", l)]
    if nx: out += ["- NEXT STEPS, newest first: " + ", ".join("%s %d" % (l.split(".")[0], n) for n, l in nx[:10])]
    out += ["- Newest entries:"] + ["  - 0a%d line %d: %s" % (k, n, short(re.sub(r"^0a\d+\.\s*", "", t), 110)) for k, n, t in ent[:12]]
    allk = sorted(ent)
    out += ["- All 0a entries (number line): " + ", ".join("0a%d %d" % (k, n) for k, n, _ in allk[i:i + 30]) for i in range(0, len(allk), 30)]
    return out + [""]

def toc_index(body, off, name):
    S = sections(body, off); out = ["**Contents of %s** (line numbers; read a part with `sed -n 'A,Bp' docs/%s | cut -c1-800`)" % (name, name), ""]
    for n, t, e in S:
        out.append("- %s: lines %d-%d" % (short(t, 70), n, e))
        sub = [(i + off, l[4:]) for i, l in enumerate(body) if l.startswith("### ") and n < i + off <= e]
        out += ["  - %s: line %d" % (short(st, 80), m) for m, st in sub]
        if t.startswith("1. Status"):
            st = [(i + off, l) for i, l in enumerate(body) if l.startswith("- **") and n < i + off <= e]
            out += ["  - newest status entries: " + "; ".join("%d %s" % (m, short(l[2:], 60)) for m, l in st[:8])]
    return out + [""]

def toc_lessons(body, off, name):
    S = sections(body, off); out = ["**Contents of %s** (line numbers; read a part with `sed -n 'A,Bp' docs/%s | cut -c1-800`)" % (name, name), ""]
    for n, t, e in S:
        out.append("- %s: lines %d-%d" % (short(t, 70), n, e))
        if t.startswith("9."):
            it = [(i + off, l) for i, l in enumerate(body) if l.startswith("- ") and n < i + off <= e]
            out += ["  - %d entries, newest at the END; the last 12: " % len(it) + "; ".join("%d %s" % (m, short(l[2:], 50)) for m, l in it[-12:])]
    return out + [""]

KIND = {"HANDOFF.md": toc_handoff, "INDEX.md": toc_index, "LESSONS.md": toc_lessons}

def render(path):
    name = os.path.basename(path); lines = strip_block(open(path, encoding="utf-8").read().split("\n"))
    head, body = lines[:1], lines[1:]
    L = 0
    for _ in range(6):   # the block's own length shifts the line numbers below it: body[0] lands on line 1 (title) + len(block) + 1
        blk = [B0] + KIND[name](body, L + 2, name) + [B1, ""]
        if len(blk) == L: break
        L = len(blk)
    return "\n".join(head + blk + body)

def main():
    a = sys.argv[1:]; chk = "--check" in a; a = [x for x in a if x != "--check"]
    files = a or [os.path.join(DOCS, f) for f in KIND]; bad = 0
    for p in files:
        new = render(p); old = open(p, encoding="utf-8").read()
        if new == old: continue
        if chk: print("TOC stale: %s (run: python3 tools/make_toc.py)" % os.path.basename(p)); bad = 1
        else: open(p, "w", encoding="utf-8").write(new); print("TOC written: %s" % os.path.basename(p))
    sys.exit(bad)

if __name__ == "__main__":
    main()
