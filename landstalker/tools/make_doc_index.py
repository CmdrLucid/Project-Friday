#!/usr/bin/env python3
"""Writes docs/DEBUGGING_INDEX.md: all headings of docs/DEBUGGING.md with line numbers (it is a 780+ line evidence log).
usage: python3 tools/make_doc_index.py   (run after editing DEBUGGING.md; see HANDOFF 3b)"""
import os, re
d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs")
out = ["# DEBUGGING.md index (generated by tools/make_doc_index.py; line numbers go stale, regenerate)\n"]
for n, l in enumerate(open(os.path.join(d, "DEBUGGING.md"), encoding="utf-8"), 1):
    m = re.match(r"(#{2,3}) (.*)", l)
    if m: out.append(f"{'  ' * (len(m.group(1)) - 2)}- L{n}: {m.group(2).strip()}")
open(os.path.join(d, "DEBUGGING_INDEX.md"), "w").write("\n".join(out) + "\n")
print(len(out) - 1, "headings")
