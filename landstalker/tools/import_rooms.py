#!/usr/bin/env python3
"""Room numbers -> names. Reads constants/map_codes.hpp of Dinopony/landstalker-lib (local clone, default ~/landstalker-lib)
and writes docs/rooms.json (id -> name) and docs/ROOMS.md (grouped table). Our own observations live in OBSERVED below
(room ids as the coordinate overlay shows them, decimal = g_RmNum1 $FF1204). Re-run after editing OBSERVED.
Usage: python3 tools/import_rooms.py [~/landstalker-lib]"""
import json, os, re, sys

LIB = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/landstalker-lib")
DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs")
OBSERVED = {  # id: what we saw (user / replay), see FORMATS.md section 2
    597: "save of the old replay loads here (church), user 2026-10-11",
    603: "overlay ROOM 603 in Gumi (church entrance, guard), user 2026-10-11",
    607: "save slot 1 'Gumi' loads here, priest dialogue",
    610: "overlay in Ryuma, user 2026-10-11",
    224: "treasure room with chests, overlay, user 2026-10-11 (thieves' hideout)",
    533: "room before Tibor, overlay, user 2026-10-11",
    815: "inside Tibor, first room, overlay, user 2026-10-11",
    185: "first room of the thieves' hideout, overlay, user 2026-10-11",
    430: "shadow flicker test room (X 29.0A Y 29.0B Z 0010), user 2026-10-13",
}
rooms = {}
for l in open(os.path.join(LIB, "constants", "map_codes.hpp")):
    m = re.match(r"constexpr uint16_t (MAP_\w+) = (\d+);", l)
    if m: rooms[int(m.group(2))] = m.group(1)[4:]
names = {i: n for i, n in rooms.items() if not n.isdigit()}
json.dump({"source": "Dinopony/landstalker-lib constants/map_codes.hpp (US/EU room ids, decimal)",
           "rooms": {str(i): n for i, n in sorted(rooms.items())}}, open(os.path.join(DOCS, "rooms.json"), "w"), indent=0)
out = ["# Room numbers\n",
       "Generated by `tools/import_rooms.py` from `constants/map_codes.hpp` of [Dinopony/landstalker-lib](https://github.com/Dinopony/landstalker-lib) "
       "(thanks!) plus our own observations. Decimal = what the coordinate overlay (R4 / F5) shows; hex = `g_RmNum1 $FF1204`. "
       f"{len(rooms)} rooms, {len(names)} with a name (the rest are plain numbers in the source: `-`).\n",
       "Where the library and our observations were checked against each other they agree (597 church, 603 Gumi, 607 Gumi church, 610 Ryuma). "
       "Names are the library's identifiers (upper case, underscores).\n",
       "| room | hex | name | observed by us |", "|---|---|---|---|"]
for i in sorted(rooms):
    n = rooms[i]
    if n.isdigit() and i not in OBSERVED: continue
    out.append(f"| {i} | ${i:04X} | {'-' if n.isdigit() else n} | {OBSERVED.get(i, '')} |")
out.append("\nRooms listed only by number in the library are omitted here (see `rooms.json`).")
open(os.path.join(DOCS, "ROOMS.md"), "w").write("\n".join(out) + "\n")
print(len(rooms), "rooms,", len(names), "named; observed:", {i: rooms.get(i) for i in OBSERVED})
